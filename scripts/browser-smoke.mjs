// Full UI, audio, and two-player regression using installed Chrome.
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { createApp } from '../server.mjs';
import { createBrowserSession } from './browser-tools.mjs';
const app = process.env.TEST_URL ? null : createApp();
if (app) { app.server.listen(0, '127.0.0.1'); await once(app.server, 'listening'); }
const { page, send, pause, errors, close, soundCount, soundDurations } = await createBrowserSession(process.env.TEST_URL || `http://127.0.0.1:${app.server.address().port}`);

try {
  const a = await page(1440, 1050);
  await a.noOverflow();
  await a.screenshot('desktop');
  assert.equal(await soundCount(a, 'welcome'), 0, 'No opening audio before interaction');
  await a.click('[data-nav="rules"]');
  await a.wait('window.smokeEffects.length === 1');
  assert.equal(await soundCount(a, 'welcome'), 1, `Expected welcome ${soundDurations.welcome}s; played ${JSON.stringify(await a.evaluate('window.smokeEffects'))}`);
  assert.equal(await a.evaluate('document.querySelector("#info-dialog").open'), true);
  await a.click('.dialog-close');
  assert.equal(await soundCount(a, 'welcome'), 1, 'Opening audio must not repeat on every click');
  await a.click('[data-page="profile"]');
  await a.fill('#profile-name', 'Alice');
  await a.click('#profile-form button[type="submit"]');
  await a.wait(`fetch("/api/me").then(r=>r.json()).then(d=>d.profile.name === "Alice")`);
  await a.evaluate(`(async () => {
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = 32;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#c7aa72'; ctx.fillRect(0,0,32,32);
    const blob = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'));
    const files = new DataTransfer(); files.items.add(new File([blob], 'avatar.png', {type:'image/png'}));
    const input = document.querySelector('#avatar-file'); input.files = files.files;
    input.dispatchEvent(new Event('change', {bubbles:true}));
  })()`);
  await a.wait('document.querySelector(".avatar-large img")');
  assert.match(await a.evaluate('fetch("/api/me").then(r=>r.json()).then(d=>d.profile.avatar)'), /^data:image\/jpeg;base64,/);
  await a.screenshot('profile');
  await a.click('.page-back');
  await a.click('[data-page="heroes"]');
  assert.equal(await a.evaluate('document.querySelectorAll(".library-card").length'), 8);
  for (const hero of ['golar']) {
    await a.click(`[data-action="hero-details"][data-hero="${hero}"]`);
    assert.match(await a.evaluate('document.querySelector("#dialog-content").textContent'), /Deadly Slash/);
    assert.equal(await a.evaluate('document.querySelector("#dialog-content h2").textContent'), hero.toUpperCase());
    await a.click('.dialog-close');
  }
  await a.noOverflow();
  await a.screenshot('hero-library');
  await a.click('.page-back');
  for (const [pageName, selector] of [['events', '.coming-panel'], ['points', '.coin-summary'], ['leaderboard', '.leaderboard-entry']]) {
    await a.click(`[data-page="${pageName}"]`);
    await a.wait(`document.querySelector('${selector}')`);
    await a.noOverflow();
    await a.click('.page-back');
  }
  await a.click('[data-page="settings"]');
  await a.evaluate('window.OriginalAudio = window.Audio; window.Audio = function (...args) { window.smokeAudio = new window.OriginalAudio(...args); return window.smokeAudio; };');
  await a.click('[data-action="toggle-bgm"]');
  await a.wait('window.smokeAudio && !window.smokeAudio.paused && window.smokeAudio.currentTime > 0');
  assert.equal(await a.evaluate('new URL(window.smokeAudio.currentSrc).pathname'), '/assets/Audios/BGM.mp3');
  assert.equal(await a.evaluate('window.smokeAudio.loop'), true);
  assert.equal(await a.evaluate('localStorage.getItem("empire.bgm")'), 'on');
  await a.click('[data-action="toggle-bgm"]');
  await a.wait('window.smokeAudio?.paused');
  await a.screenshot('settings');
  await send('Page.reload', {}, a.sessionId);
  await a.wait('document.querySelector(".settings-panel")');
  assert.equal(await a.evaluate('document.querySelector("[role=switch]").getAttribute("aria-checked")'), 'false');
  await a.click('.page-back');
  await a.click('.menu-play');
  const b = await page(390, 844);
  await b.noOverflow();
  await b.screenshot('mobile');
  await b.click('[data-page="heroes"]');
  await b.noOverflow();
  await b.screenshot('mobile-hero-library');
  await b.click('.page-back');
  await b.click('.menu-play');
  await a.click('[data-action="choose-spell"][data-spell="execute"]');
  await b.click('[data-action="choose-spell"][data-spell="execute"]');
  await a.fill('#player-name', 'Alice');
  await a.click('#create-form button[type="submit"]');
  await a.wait('document.querySelector(".room-code-big")');
  const code = await a.evaluate('document.querySelector(".room-code-big").textContent.trim()');
  await b.fill('#player-name', 'Bob');
  await b.click('[data-action="choose-hero"][data-hero="roger"]');
  await b.fill('#room-code', code);
  await b.click('#join-form button[type="submit"]');
  await b.wait('document.querySelector(".room-code-big")');
  await b.noOverflow();
  await a.click('[data-action="ready"]');
  await b.click('[data-action="ready"]');
  await a.wait('document.querySelectorAll(".skill-card").length === 3');
  await b.wait('document.querySelectorAll(".skill-card").length === 3');
  assert.equal(await a.evaluate('document.querySelectorAll(".hero-formation .formation-hero img").length'), 2);
  assert.equal(await a.evaluate('document.querySelectorAll(".ultimate-slot.is-inactive:disabled").length'), 2);
  assert.equal(await a.evaluate('document.querySelectorAll(".spell-slot").length'), 2);
  await a.click('[data-skill="lightning"]');
  await a.click('[data-action="lock"]');
  await a.wait('document.querySelector(".battle-slot.locked")');
  await a.wait(`window.smokeEffects.some(duration => Math.abs(duration - ${soundDurations.lock}) < 0.002)`);
  assert.equal(await soundCount(a, 'lock'), 1);
  await b.wait('document.querySelectorAll(".battle-slot.locked").length === 1');
  assert.equal(await b.evaluate('document.querySelector(".battle-slot.locked img").alt'), 'Kartu skill tertutup');
  assert.equal(await a.evaluate('document.querySelector(".your-side .energy-meter .energy-pips").querySelectorAll(".filled").length'), 2);
  assert.equal(await b.evaluate('document.querySelector(".rival-side .energy-meter .energy-pips").querySelectorAll(".filled").length'), 3);
  const { identifier: offlineScript } = await send('Page.addScriptToEvaluateOnNewDocument', {
    source: `const originalFetch = window.fetch; let failHealth = true; window.fetch = (...args) => { if (failHealth && String(args[0]).includes('/api/health')) { failHealth = false; return Promise.reject(new TypeError('Simulated reconnect')); } return originalFetch(...args); };`,
  }, a.sessionId);
  await send('Page.reload', {}, a.sessionId);
  await a.wait('document.querySelector(".battle-slot.locked")');
  await a.wait('document.querySelector("#connection-label").textContent === "Arena online"');
  await send('Page.removeScriptToEvaluateOnNewDocument', { identifier: offlineScript }, a.sessionId);
  await b.click('[data-skill="bom"]');
  const lockedAt = Date.now();
  await b.click('[data-action="lock"]');
  await a.wait('document.querySelector(".counting")');
  assert.equal(await a.evaluate('document.querySelectorAll(".face-up").length'), 0);
  const countdown = Number(await a.evaluate('document.querySelector("#countdown-value").textContent'));
  assert.ok(countdown >= 3 && countdown <= 4);
  await b.noOverflow();
  await b.screenshot('mobile-countdown');
  await a.wait('document.querySelectorAll(".face-up").length === 2');
  assert.ok(Date.now() - lockedAt >= 3900, 'Cards revealed before four seconds');
  await b.wait('document.querySelectorAll(".face-up").length === 2');
  const hp = async tab => tab.evaluate('[...document.querySelectorAll(".hp-row b")].map(el => Number(el.textContent))');
  const aliceHp = await hp(a);
  const bobHp = await hp(b);
  assert.equal(aliceHp[0], 160);
  assert.equal(aliceHp[1], 120);
  assert.deepEqual(aliceHp, bobHp.reverse());
  assert.deepEqual(await a.evaluate('[...document.querySelectorAll(".defense-row b")].map(el => Number(el.textContent))'), [55, 10]);
  assert.match(await b.evaluate('document.querySelector(".your-side .status-effects").textContent'), /STUN/);
  await pause(850); // Capture the fully revealed cards after the flip animation.
  await a.screenshot('battle');
  await b.screenshot('mobile-battle');
  await a.noOverflow();
  await b.noOverflow();
  await a.wait('document.querySelectorAll(".skill-card:not(:disabled)").length === 3');
  assert.equal(await a.evaluate('document.querySelector(".round-counter strong").textContent'), '02');
  await b.wait('document.querySelector(".stunned-slot")');
  assert.equal(await b.evaluate('document.querySelectorAll(".skill-card:not(:disabled)").length'), 0);
  await a.click('[data-skill="ultimate"]');
  await a.click('[data-action="lock"]');
  await a.wait('document.querySelector(".counting")');
  await a.wait('document.querySelectorAll(".face-up").length === 1');
  const secondHp = await hp(a);
  assert.equal(secondHp[0], 160);
  assert.ok(secondHp[1] >= 85 && secondHp[1] <= 90);
  await a.wait('document.querySelector(".round-counter strong").textContent === "03"');
  await b.wait('document.querySelectorAll(".skill-card:not(:disabled)").length === 3');
  await a.click('[data-skill="silent"]');
  await a.click('[data-action="lock"]');
  await b.click('[data-skill="free-fire"]');
  await b.click('[data-action="lock"]');
  await a.wait('document.querySelectorAll(".face-up").length === 2');
  await b.wait('document.querySelectorAll(".face-up").length === 2');
  await pause(850);
  assert.match(await a.evaluate('document.querySelector(".your-side .guard-status").textContent'), /10% DMG · 2/);
  assert.equal((await hp(a))[1], secondHp[1] - 10);
  await a.screenshot('counter-arena');
  await b.screenshot('mobile-counter-arena');
  await a.noOverflow();
  await b.noOverflow();
  // Finish naturally, then rematch and forfeit to verify both result paths.
  for (const round of ['04']) {
    await a.wait(`document.querySelector('.round-counter strong').textContent === '${round}'`);
    await b.wait('document.querySelectorAll(".skill-card:not(:disabled)").length > 0');
    await a.click('[data-skill="ultimate"]');
    await a.click('[data-action="lock"]');
    await b.click('[data-skill="long-fire"]');
    await b.click('[data-action="lock"]');
    await a.wait('document.querySelector(".result-screen")');
  }
  await a.wait('document.querySelector(".result-screen")');
  await b.wait('document.querySelector(".result-screen")');
  await a.wait(`window.smokeEffects.some(duration => Math.abs(duration - ${soundDurations.victory}) < 0.002)`);
  await b.wait(`window.smokeEffects.some(duration => Math.abs(duration - ${soundDurations.defeat}) < 0.002)`);
  assert.equal(await soundCount(a, 'victory'), 1);
  assert.equal(await soundCount(a, 'defeat'), 0);
  assert.equal(await soundCount(b, 'defeat'), 1);
  assert.equal(await soundCount(b, 'victory'), 0);
  await send('Page.reload', {}, a.sessionId);
  await a.wait('document.querySelector(".result-screen")');
  await a.click('[data-nav="rules"]');
  await a.click('.dialog-close');
  assert.equal(await soundCount(a, 'victory'), 1, 'Refresh must not replay the result');
  await a.click('[data-action="rematch"]');
  await b.click('[data-action="rematch"]');
  for (const tab of [a,b]) await tab.wait('document.querySelector(".room-code-big")');
  await a.click('[data-action="ready"]'); await b.click('[data-action="ready"]');
  await a.wait('document.querySelectorAll(".skill-card:not(:disabled)").length === 3');
  await b.wait('document.querySelectorAll(".skill-card:not(:disabled)").length === 3');
  await b.click('[data-action="leave"]');
  await b.click('[data-action="confirm-leave"]');
  await a.wait('document.querySelector(".result-screen")');
  assert.match(await a.evaluate('document.querySelector(".result-screen h1").textContent'), /menang/i);
  await b.wait('document.querySelector(".menu-layout")');
  await a.wait(`window.smokeEffects.filter(duration => Math.abs(duration - ${soundDurations.victory}) < 0.002).length === 2`);
  await b.wait(`window.smokeEffects.filter(duration => Math.abs(duration - ${soundDurations.defeat}) < 0.002).length === 2`);
  await a.click('[data-action="leave"]');
  await a.click('[data-action="confirm-leave"]');
  assert.equal(await soundCount(a, 'victory'), 2, 'Leaving the results screen must not replay victory');
  assert.deepEqual(errors, [], 'Browser runtime or network errors');
  console.log('PASS: menu/profile/BGM, responsive arena, opening and lock sounds, two-client knockout and forfeit with separate victory/defeat audio, result deduplication after refresh, rematch, and duel regression.');
} finally {
  await close();
  if (app) { app.dispose(); await new Promise(resolve => app.server.close(resolve)); await app.closeStore(); }
}
